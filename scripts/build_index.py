#!/usr/bin/env python3
"""Build INDEX.md: the weekly recaps (newest first) and every non-example module with its status.

Usage:
  python3 scripts/build_index.py           write INDEX.md
  python3 scripts/build_index.py --check   exit 1 if INDEX.md is out of date
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from howtolib import ISSUES_URL, ROOT, SITE_URL, Module, Recap, first_lesson_path, load_modules, load_recaps

INDEX = ROOT / "INDEX.md"
STATUS_ORDER = {"tested": 0, "draft": 1, "seed": 2}


def cell(value: str) -> str:
    return value.replace("|", "\\|")


def render(root: Path, recaps: list[Recap], modules: list[Module]) -> str:
    out = [
        "# Index",
        "",
        "The weekly recaps and every community module in the repo. Generated by "
        "`scripts/build_index.py`, so don't edit it by hand. "
        f"Browse it on the site: {SITE_URL}",
        "",
        "## Recaps",
        "",
    ]
    if recaps:
        out += ["Newest first.", "", "| Week | Recap |", "|---|---|"]
        for recap in recaps:
            link = recap.path.relative_to(root).as_posix()
            out.append(f"| {recap.week} | [{cell(recap.title)}]({link}) |")
    else:
        out.append("No recaps yet.")

    out += ["", "## Modules", ""]
    real = [m for m in modules if not m.example]
    if real:
        out += [
            "Tested first, then draft, then seed.",
            "",
            "| Module | Status | Tags | Difficulty | Contributors | Recap |",
            "|---|---|---|---|---|---|",
        ]
        real.sort(key=lambda m: (STATUS_ORDER.get(m.howto.get("status"), 9), m.id))
        for module in real:
            meta = module.howto
            link = first_lesson_path(module).relative_to(root).as_posix()
            out.append(
                f"| [{cell(meta['title'])}]({link}) | {meta['status']} | {cell(', '.join(meta['tags']))} "
                f"| {meta['difficulty']} | {cell(', '.join(meta['contributors']))} | {meta.get('recap', '')} |"
            )
    else:
        out.append(
            "No community modules yet. Pick one from the "
            f"[open module issues]({ISSUES_URL}) and see [CONTRIBUTING.md](CONTRIBUTING.md)."
        )
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build INDEX.md from recaps/ and modules/*/howto.json.")
    parser.add_argument("--check", action="store_true", help="exit 1 if INDEX.md would change")
    args = parser.parse_args()

    recaps = load_recaps(ROOT / "recaps")
    modules = load_modules(ROOT)
    text = render(ROOT, recaps, modules)
    real = sum(not m.example for m in modules)
    current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else None

    if args.check:
        if current != text:
            print("INDEX.md is out of date. Run: python3 scripts/build_index.py", file=sys.stderr)
            return 1
        print(f"INDEX.md is up to date ({len(recaps)} recaps, {real} modules)")
        return 0

    INDEX.write_text(text, encoding="utf-8")
    print(f"INDEX.md: {len(recaps)} recaps, {real} modules")
    return 0


if __name__ == "__main__":
    sys.exit(main())
